/**
 * 根据出生年份查纳音五行
 * @param {string} birthday 含年份
 * @returns {object|null} { nayin, element(金木水火土) }
 */
function getNayin(birthday) {
  if (!birthday) return null
  const m = birthday.match(/^(\d{4})/)
  if (!m) return null
  const year = parseInt(m[1])
  const nayin = NAYIN_BY_YEAR[year]
  if (!nayin) return null
  // 提取五行元素
  const element = nayin[nayin.length - 1] // 末字(金木水火土)
  return { nayin, element }
}

