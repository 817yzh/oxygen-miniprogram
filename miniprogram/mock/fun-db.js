/**
 * 根据生日(MM-DD)查星座
 * @param {string} birthday 如 '2004-06-15' 或 '06-15' 或 '6/15'
 * @returns {object|null} 星座对象
 */
function getZodiac(birthday) {
  if (!birthday) return null
  // 提取 MM-DD 或 MM/DD（忽略年份前缀，防止把年份的“04”误当月份）
  const m = birthday.match(/(1[0-2]|0?[1-9])[\-/](3[01]|[12][0-9]|0?[1-9])[^\d]*$/)
  if (!m) return null
  const md = (m[1].padStart(2, '0') + '-' + m[2].padStart(2, '0'))
  // 摩羯跨年(12-22 ~ 01-19)
  if (md >= '01-01' && md <= '01-19') return ZODIAC[ZODIAC.length - 1]
  if (md >= '12-22') return ZODIAC[ZODIAC.length - 1]
  return ZODIAC.find(z => md >= z.start && md <= z.end) || null
}

